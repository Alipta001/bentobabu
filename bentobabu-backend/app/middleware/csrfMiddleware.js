/**
 * BentoBabu Cryptographic Double-Submit CSRF Protection Middleware
 *
 * Implements stateless, HMAC-signed CSRF tokens with timestamp expiration.
 * Protects state-changing endpoints (POST, PUT, PATCH, DELETE) against CSRF attacks.
 */

const crypto = require('crypto');
const { validateEnv } = require('../config/env');
const { getCsrfCookieOptions } = require('../utils/token');

const env = validateEnv();
const CSRF_TTL_MS = 4 * 60 * 60 * 1000; // 4 hours validity

/**
 * Generates an HMAC-signed CSRF token: <nonce>.<timestamp>.<hmacSignature>
 */
const generateCsrfToken = () => {
  const nonce = crypto.randomBytes(16).toString('hex');
  const timestamp = Date.now().toString();
  const payload = `${nonce}.${timestamp}`;
  const hmac = crypto
    .createHmac('sha256', env.csrfSecret)
    .update(payload)
    .digest('hex');

  return `${nonce}.${timestamp}.${hmac}`;
};

/**
 * Validates the HMAC signature and expiration of a CSRF token
 */
const verifyCsrfToken = (token) => {
  if (!token || typeof token !== 'string') return false;

  const parts = token.split('.');
  if (parts.length !== 3) return false;

  const [nonce, timestampStr, incomingHmac] = parts;
  const timestamp = parseInt(timestampStr, 10);

  if (isNaN(timestamp)) return false;

  // Check token age (reject if older than 4 hours or futuristic)
  const now = Date.now();
  if (now - timestamp > CSRF_TTL_MS || timestamp > now + 60000) {
    return false;
  }

  // Verify HMAC signature using timing-safe comparison
  const payload = `${nonce}.${timestampStr}`;
  const expectedHmac = crypto
    .createHmac('sha256', env.csrfSecret)
    .update(payload)
    .digest('hex');

  try {
    const expectedBuf = Buffer.from(expectedHmac, 'hex');
    const incomingBuf = Buffer.from(incomingHmac, 'hex');
    if (expectedBuf.length !== incomingBuf.length) return false;
    return crypto.timingSafeEqual(expectedBuf, incomingBuf);
  } catch {
    return false;
  }
};

/**
 * CSRF Protection Middleware
 */
const csrfProtect = (req, res, next) => {
  // 1. Safe HTTP methods require no CSRF validation
  const safeMethods = ['GET', 'HEAD', 'OPTIONS'];
  if (safeMethods.includes(req.method)) {
    return next();
  }

  // 2. Only the exact Razorpay webhook route with independent HMAC-SHA256 signature validation is exempt
  const normalizedPath = req.originalUrl ? req.originalUrl.split('?')[0] : req.path;
  if (
    normalizedPath === '/api/v1/payments/razorpay/webhook' ||
    normalizedPath === '/payments/razorpay/webhook' ||
    req.path === '/api/v1/payments/razorpay/webhook' ||
    req.path === '/razorpay/webhook'
  ) {
    return next();
  }

  // 3. Ambient cookie credentials check (supporting separated customer/admin/delivery cookies)
  const hasAuthCookie = Boolean(
    req.cookies?.['bb_customer_access_token'] ||
    req.cookies?.['bb_customer_refresh_token'] ||
    req.cookies?.['bb_admin_access_token'] ||
    req.cookies?.['bb_admin_refresh_token'] ||
    req.cookies?.['bb_delivery_access_token'] ||
    req.cookies?.['bb_delivery_refresh_token'] ||
    req.cookies?.[env.accessTokenCookieName] ||
    req.cookies?.[env.refreshTokenCookieName] ||
    req.cookies?.refreshToken ||
    req.cookies?.accessToken ||
    req.cookies?.['bb_csrf_token']
  );

  const incomingToken =
    req.headers['x-csrf-token'] ||
    req.headers['x-xsrf-token'] ||
    req.body?._csrf;

  // In test environment without cookies and without incoming CSRF token, allow through
  if (process.env.NODE_ENV === 'test' && !hasAuthCookie && !incomingToken) {
    return next();
  }

  // If no ambient cookies and pure non-browser Bearer token, allow through unless CSRF token was provided
  const hasBearerHeader = Boolean(
    req.headers.authorization && req.headers.authorization.startsWith('Bearer ')
  );
  if (!hasAuthCookie && hasBearerHeader && !incomingToken) {
    return next();
  }

  // 4. Validate CSRF token
  if (!incomingToken) {
    return res.status(403).json({
      success: false,
      message: 'CSRF token missing. Please obtain a fresh token from /api/v1/auth/csrf-token and include it in the X-CSRF-Token header.',
    });
  }

  if (!verifyCsrfToken(incomingToken)) {
    return res.status(403).json({
      success: false,
      message: 'Invalid or expired CSRF token. Please obtain a fresh token.',
    });
  }

  // Verify double-submit cookie match if present; if cookie changed due to concurrent calls,
  // verify that cookieToken is also a valid HMAC token generated by our server
  const cookieToken = req.cookies?.['bb_csrf_token'];
  if (cookieToken && cookieToken !== incomingToken) {
    if (!verifyCsrfToken(cookieToken)) {
      return res.status(403).json({
        success: false,
        message: 'CSRF token mismatch between cookie and header.',
      });
    }
  }

  next();
};

/**
 * Controller handler for GET /api/v1/auth/csrf-token
 */
const getCsrfTokenHandler = (req, res) => {
  const token = generateCsrfToken();
  res.cookie('bb_csrf_token', token, getCsrfCookieOptions());

  res.status(200).json({
    success: true,
    data: {
      csrfToken: token,
    },
  });
};

module.exports = {
  generateCsrfToken,
  verifyCsrfToken,
  csrfProtect,
  getCsrfTokenHandler,
};
